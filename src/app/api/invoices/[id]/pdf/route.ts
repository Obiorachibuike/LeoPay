import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { requirePermission } from "@/lib/auth/context";
import { getInvoiceWithItems } from "@/services/invoices";
import { formatDate } from "@/lib/dates";
import { fromMinorUnits } from "@/lib/money";
import { toErrorResponse } from "@/lib/errors";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * Server-generated invoice PDF. Amounts are rendered with the ISO currency code
 * because the standard PDF fonts do not include every currency glyph.
 */
export async function GET(_request: Request, { params }: { params: Promise<{ id: string }> }) {
  try {
    const ctx = await requirePermission("invoice:read");
    const { id } = await params;
    const data = await getInvoiceWithItems(ctx.organization.id, id);
    if (!data) {
      return Response.json({ error: { code: "NOT_FOUND", message: "Invoice not found" } }, { status: 404 });
    }
    const { invoice, items } = data;

    const pdf = await PDFDocument.create();
    const page = pdf.addPage([595.28, 841.89]); // A4
    const font = await pdf.embedFont(StandardFonts.Helvetica);
    const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
    const ink = rgb(0.043, 0.071, 0.125);
    const muted = rgb(0.42, 0.47, 0.53);
    const line = rgb(0.88, 0.9, 0.92);

    const money = (minor: number) =>
      `${invoice.currency} ${fromMinorUnits(minor, invoice.currency).replace(/\B(?=(\d{3})+(?!\d))/g, ",")}`;

    let y = 800;
    page.drawText(ctx.organization.name, { x: 48, y, size: 16, font: bold, color: ink });
    y -= 16;
    page.drawText("Invoice", { x: 48, y, size: 10, font, color: muted });
    page.drawText(invoice.invoiceNumber, { x: 48, y: y - 14, size: 12, font: bold, color: ink });

    page.drawText("BILL TO", { x: 340, y: 800, size: 8, font, color: muted });
    page.drawText(invoice.customerName ?? "", { x: 340, y: 786, size: 11, font: bold, color: ink });
    if (invoice.customerEmail) page.drawText(invoice.customerEmail, { x: 340, y: 772, size: 9, font, color: muted });

    y -= 44;
    page.drawText(`Issued ${formatDate(invoice.issueDate)}`, { x: 48, y, size: 9, font, color: muted });
    page.drawText(invoice.dueDate ? `Due ${formatDate(invoice.dueDate)}` : "Due on receipt", {
      x: 340,
      y,
      size: 9,
      font,
      color: muted,
    });
    page.drawText(`Status: ${invoice.status}`, { x: 340, y: y - 14, size: 9, font, color: muted });

    y -= 40;
    page.drawLine({ start: { x: 48, y }, end: { x: 548, y }, thickness: 1, color: line });
    y -= 18;
    page.drawText("DESCRIPTION", { x: 48, y, size: 8, font, color: muted });
    page.drawText("QTY", { x: 380, y, size: 8, font, color: muted });
    page.drawText("UNIT", { x: 430, y, size: 8, font, color: muted });
    page.drawText("AMOUNT", { x: 495, y, size: 8, font, color: muted });

    for (const item of items) {
      y -= 18;
      const description = item.description.slice(0, 60);
      page.drawText(description, { x: 48, y, size: 10, font, color: ink });
      page.drawText(String(Number(item.quantity)), { x: 380, y, size: 10, font, color: ink });
      page.drawText(money(item.unitAmountMinor), { x: 430, y, size: 10, font, color: ink });
      page.drawText(money(item.amountMinor), { x: 495, y, size: 10, font, color: ink });
      if (y < 140) break;
    }

    y -= 20;
    page.drawLine({ start: { x: 320, y }, end: { x: 548, y }, thickness: 1, color: line });
    const rows: Array<[string, string]> = [
      ["Subtotal", money(invoice.subtotalMinor)],
      ["Discount", `-${money(invoice.discountMinor)}`],
      [`Tax (${invoice.taxRateBps / 100}%)`, money(invoice.taxMinor)],
      ["Total", money(invoice.totalMinor)],
      ["Paid", money(invoice.amountPaidMinor)],
      ["Outstanding", money(invoice.totalMinor - invoice.amountPaidMinor)],
    ];
    for (const [label, value] of rows) {
      y -= 16;
      const isTotal = label === "Total" || label === "Outstanding";
      page.drawText(label, { x: 320, y, size: 10, font: isTotal ? bold : font, color: isTotal ? ink : muted });
      page.drawText(value, { x: 430, y, size: 10, font: isTotal ? bold : font, color: isTotal ? ink : muted });
    }

    if (invoice.notes) {
      y -= 32;
      page.drawText("Notes", { x: 48, y, size: 9, font: bold, color: ink });
      page.drawText(invoice.notes.slice(0, 110), { x: 48, y: y - 14, size: 9, font, color: muted });
    }

    page.drawText("Generated by LeoPay. Amounts are in minor-unit-backed currency values.", {
      x: 48,
      y: 40,
      size: 7,
      font,
      color: muted,
    });

    const bytes = await pdf.save();
    return new Response(Buffer.from(bytes), {
      headers: {
        "content-type": "application/pdf",
        "content-disposition": `attachment; filename="${invoice.invoiceNumber}.pdf"`,
        "cache-control": "no-store",
      },
    });
  } catch (error) {
    const normalized = toErrorResponse(error);
    return Response.json({ error: { code: normalized.code, message: normalized.message } }, { status: normalized.status });
  }
}
